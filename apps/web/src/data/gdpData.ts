function interpolate(data: Record<number, number>, year: number): number | null {
  const years = Object.keys(data).map(Number).sort((a, b) => a - b);
  if (!years.length) return null;
  if (year <= years[0]!) return data[years[0]!]!;
  if (year >= years[years.length - 1]!) return data[years[years.length - 1]!]!;
  for (let i = 0; i < years.length - 1; i++) {
    const y0 = years[i]!, y1 = years[i + 1]!;
    if (year >= y0 && year <= y1) {
      const t = (year - y0) / (y1 - y0);
      return (data[y0]! * (1 - t)) + (data[y1]! * t);
    }
  }
  return null;
}

function fmtGdp(bn: number): string {
  if (bn >= 1000) return `$${(bn / 1000).toFixed(1)}T`;
  return `$${Math.round(bn)}B`;
}

export function getGdpEstimate(iso3: string, year: number): string | null {
  const data = GDP_CHECKPOINTS[iso3];
  if (!data) return null;
  const val = interpolate(data, year);
  if (val == null || val <= 0) return null;
  return `${fmtGdp(Math.round(val / 10) * 10)} est.`;
}

export function getGdpValue(iso3: string, year: number): number | null {
  const data = GDP_CHECKPOINTS[iso3];
  if (!data) return null;
  return interpolate(data, year);
}
